#!/usr/bin/env python3
"""Writes Sources/TopophanyThemes/BrandMarkData.swift from design/assets/mark.svg.

The mark as data, so BrandMark draws it as vectors at any size, in the
panel and in widgets alike. mark.svg is Topophany's favicon, as its
scripts/icon.py draws it; this reads the little of SVG that uses, and
stops on anything else.

    python3 -I scripts/make-mark.py
"""
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SVG = "{http://www.w3.org/2000/svg}"
NUMBER = r"-?[\d.]+"

svg = ET.parse(os.path.join(ROOT, "design", "assets", "mark.svg")).getroot()
assert svg.get("viewBox") == "0 0 64 64", svg.get("viewBox")
defs = {e.get("id"): e for e in svg.find(SVG + "defs")}


def num(v):
    return f"{float(v):g}"


def colour(c):
    assert re.fullmatch(r"#[0-9a-f]{6}", c), c
    return "0x" + c[1:].upper()


def ref(v):
    return defs[re.fullmatch(r"url\(#([\w-]+)\)", v)[1]]


def stops(g):
    return "[" + ", ".join(f"({num(s.get('offset'))}, {colour(s.get('stop-color'))}, {num(s.get('stop-opacity', '1'))})"
                           for s in g) + "]"


def point(x, y):
    return f"CGPoint(x: {num(x)}, y: {num(y)})"


def shape(e):
    """The element's shape, and for a circle its centre and radius."""
    if e.tag == SVG + "circle":
        c = tuple(e.get(k) for k in ("cx", "cy", "r"))
        return f".circle({', '.join(map(num, c))})", c
    assert e.tag == SVG + "path", e.tag
    # A band: its outline, then a circle at each end drawn as two arcs.
    outline, ends = None, []
    for sub in e.get("d").split("M")[1:]:
        if "a" in sub:
            m = re.fullmatch(rf"({NUMBER}) ({NUMBER})a({NUMBER}) \3 0 1 0 ({NUMBER}) 0a\3 \3 0 1 0 -\4 0Z", sub)
            x, y, r = (float(v) for v in m.groups()[:3])
            ends.append(f"({num(x + r)}, {num(y)}, {num(r)})")
        else:
            assert outline is None and sub.endswith("Z"), sub[-20:]
            outline = ", ".join(map(num, sub[:-1].split()))
    return f".ribbon([{outline}], ends: [{', '.join(ends)}])", None


def paint(value, opacity, circle):
    if not value.startswith("url("):
        return f".color({colour(value)}, {num(opacity)})"
    assert opacity == "1", opacity
    g = ref(value)
    if g.tag == SVG + "linearGradient":
        assert g.get("gradientUnits") == "userSpaceOnUse"
        return f".linear({point(g.get('x1'), g.get('y1'))}, {point(g.get('x2'), g.get('y2'))}, {stops(g)})"
    assert g.tag == SVG + "radialGradient", g.tag
    if g.get("gradientUnits") == "userSpaceOnUse":
        cx, cy, r = g.get("cx"), g.get("cy"), g.get("r")
    else:
        # Centred on the shape's own box, reaching its edge: for a circle,
        # its centre and radius.
        assert circle and not {"cx", "cy", "r", "fx", "fy"} & set(g.keys())
        cx, cy, r = circle
    return f".radial({point(cx, cy)}, {num(r)}, {stops(g)})"


def layer(e):
    s, circle = shape(e)
    if e.get("fill") == "none":
        args = [s, paint(e.get("stroke"), e.get("stroke-opacity", "1"), circle), f"stroke: {num(e.get('stroke-width'))}"]
    else:
        args = [s, paint(e.get("fill"), e.get("fill-opacity", "1"), circle)]
    if e.get("clip-path"):
        (clip,) = ref(e.get("clip-path"))
        args.append(f"clip: {shape(clip)[0]}")
    return f"        Layer({', '.join(args)}),"


# The land's dots are most of the mark, so they go as plain numbers.
under, dots, over = [], [], []
for e in svg:
    if e.tag == SVG + "defs":
        continue
    if (e.tag == SVG + "circle" and set(e.keys()) == {"cx", "cy", "r", "fill"} and not e.get("fill").startswith("url(")
            and float(e.get("r")) < 1.5):
        assert not over, "a dot above the arc"
        dots.append(f"        ({e.get('cx')}, {e.get('cy')}, {e.get('r')}, {colour(e.get('fill'))}),")
    else:
        (over if dots else under).append(layer(e))
assert len(dots) > 200, len(dots)
lines = [
    "// Generated by scripts/make-mark.py from design/assets/mark.svg. Don't edit.",
    "",
    "import CoreGraphics",
    "",
    "extension BrandMark {",
    "    /// What lies under the land, in a 64 × 64 box.",
    "    static let under: [Layer] = [",
    *under,
    "    ]",
    "",
    "    /// The land's dots: x, y, radius and 0xRRGGBB.",
    "    static let dots: [(Double, Double, Double, UInt32)] = [",
    *dots,
    "    ]",
    "",
    "    /// What lies over the land: the atmosphere's edge, the arc and its places.",
    "    static let over: [Layer] = [",
    *over,
    "    ]",
    "}",
    "",
]
out = os.path.join(ROOT, "Sources", "TopophanyThemes", "BrandMarkData.swift")
open(out, "w", encoding="utf-8").write("\n".join(lines))
print(out, len(under), len(dots), len(over))
