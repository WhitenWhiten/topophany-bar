#!/usr/bin/env python3
"""Writes Sources/TopophanyThemes/BrandMarkData.swift from design/assets/mark.svg.

The mark's dot-matrix globe as data, so BrandMark draws it as vectors at
any size, in the panel and in widgets alike.

    python3 -I scripts/make-mark.py
"""
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
svg = open(os.path.join(ROOT, "design", "assets", "mark.svg"), encoding="utf-8").read()
dots = []
for m in re.finditer(r'<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)" fill="#([0-9a-f]{6})"/>', svg):
    cx, cy, r, color = m.groups()
    if float(r) < 1.5:
        dots.append((cx, cy, r, color))
assert len(dots) > 200, len(dots)
lines = [
    "// Generated by scripts/make-mark.py from design/assets/mark.svg. Don't edit.",
    "",
    "extension BrandMark {",
    "    /// The globe's dots in a 64 × 64 box: x, y, radius and 0xRRGGBB.",
    "    static let dots: [(Double, Double, Double, UInt32)] = [",
]
for cx, cy, r, color in dots:
    lines.append(f"        ({cx}, {cy}, {r}, 0x{color.upper()}),")
lines += ["    ]", "}", ""]
out = os.path.join(ROOT, "Sources", "TopophanyThemes", "BrandMarkData.swift")
open(out, "w", encoding="utf-8").write("\n".join(lines))
print(out, len(dots))
